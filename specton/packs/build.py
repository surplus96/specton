"""도메인 팩 생성기.

사람이 쓰는 입력(`sources/`의 공식 공통표준 CSV, 각 팩의 `term_specs.yaml`·`words.yaml`)에서
생성 파일(`common/words.yaml`, `common/domains.yaml`, `<pack>/terms.yaml`)을 만든다.
팩마다 `pack.lock`(manifest 버전 + 팩 내용 sha256)도 함께 만들어, 내용이 바뀌었는데
버전을 올리지 않은 경우를 `--check`가 잡아낸다.

    uv run python -m specton.packs.build            # 생성
    uv run python -m specton.packs.build --check    # 커밋된 생성 파일·lock이 최신인지 검사 (CI)
"""

import argparse
import csv
import hashlib
import re
import sys
from collections.abc import Iterable
from pathlib import Path
from typing import Any

import yaml

from specton.contracts.base import SqlType
from specton.packs.term_names import term_name_conflicts

Record = dict[str, Any]

DEFAULT_ROOT = Path("domain_packs")
MAX_IDENTIFIER_BYTES = 63  # PostgreSQL NAMEDATALEN - 1
LOCK_NAME = "pack.lock"
_COMMON_DIR = "common"  # specton.packs.loader.COMMON과 같은 값. 순환 import를 피하려고 따로 둔다.
RETIRED = "폐기"
RETIRED_COLUMN = "개정구분명(폐기 또는 변경)"
HANJA_PREFIX = re.compile(r"^[一-鿿/]+\.\s*")  # 영문 어원 접두어는 유지한다
GENERATED_HEADER = (
    "# GENERATED by specton.packs.build — 직접 수정하지 않는다.\n"
    "# 입력(sources/, term_specs.yaml, words.yaml)을 고친 뒤\n"
    "# `uv run python -m specton.packs.build`를 실행한다.\n"
)

# 표준 타입 → PostgreSQL.
# strict는 표준 저장 형식을 유지하고, pg_native는 PostgreSQL 고유 타입을 쓴다.
PG_NATIVE_OVERRIDES: dict[str, Record] = {
    "여부C1": {"type": "boolean"},
    "연월일C8": {"type": "date"},
    "연월일시분초D": {"type": "timestamptz", "precision": 0},
    "시분초C6": {"type": "time", "precision": 0},
    "일련번호N10": {"type": "bigint"},
}
STORAGE_FORMAT_CHECKED = {"연월일C8", "시분초C6"}


class BuildError(Exception):
    """입력이 표준 규칙을 어겨 생성할 수 없음."""


def read_yaml(path: Path) -> Record:
    data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    if not isinstance(data, dict):
        raise BuildError(f"{path}: 최상위가 매핑이 아님")
    return data


def read_csv(path: Path) -> list[dict[str, str]]:
    with path.open(encoding="utf-8-sig", newline="") as f:
        rows = list(csv.DictReader(f))
    return [r for r in rows if r.get(RETIRED_COLUMN, "").strip() != RETIRED]


def split_list(value: str) -> list[str]:
    return [v.strip() for v in value.replace(";", ",").split(",") if v.strip()]


def to_int(value: str) -> int | None:
    return int(value) if value.strip() else None


def word_entry(row: dict[str, str]) -> Record:
    return {
        "word": row["공통표준단어명"].strip(),
        "abbreviation": row["공통표준단어영문약어명"].strip(),
        "english": row["공통표준단어 영문명"].strip(),
        "definition": HANJA_PREFIX.sub("", row["공통표준단어 설명"].strip()),
        "is_classifier": row["형식단어여부"].strip() == "Y",
        "domain_group": row["공통표준도메인분류명"].strip() or None,
        "synonyms": split_list(row["이음동의어 목록"]),
        "forbidden_synonyms": split_list(row["금칙어 목록"]),
    }


def strict_type(row: dict[str, str]) -> Record:
    name = row["공통표준도메인명"].strip()
    sql = row["데이터타입"].strip().upper()
    length = to_int(row["데이터길이"])
    scale = to_int(row["데이터소수점길이"])
    if sql == "DATETIME":
        return {"type": "timestamp", "precision": 0}
    if sql == "CHAR" and name.startswith("코드"):
        return {"type": "varchar", "length": length, "check": "fixed_length"}
    spec: Record = {
        "type": {"CHAR": "char", "VARCHAR": "varchar", "NUMERIC": "numeric"}[sql],
        "length": length,
    }
    if scale is not None:
        spec["scale"] = scale
    if name == "여부C1":
        spec["check"] = "in_allowed_values"
    elif name in STORAGE_FORMAT_CHECKED:
        spec["check"] = "storage_format"
    return spec


def domain_entry(row: dict[str, str]) -> Record:
    name = row["공통표준도메인명"].strip()
    strict = strict_type(row)
    return {
        "group": row["공통표준도메인그룹명"].strip(),
        "class": row["공통표준도메인분류명"].strip(),
        "name": name,
        "standard_type": row["데이터타입"].strip(),
        "length": to_int(row["데이터길이"]),
        "scale": to_int(row["데이터소수점길이"]),
        "storage_format": row["저장형식"].strip() or None,
        "allowed_values": row["허용값"].strip() or None,
        "postgres": {"strict": strict, "pg_native": dict(PG_NATIVE_OVERRIDES.get(name, strict))},
    }


def discover_packs(root: Path) -> list[Path]:
    return sorted(p.parent for p in root.glob("*/term_specs.yaml"))


def all_pack_dirs(root: Path) -> list[Path]:
    """lock 파일을 두는 모든 팩 폴더: common + term_specs.yaml이 있는 팩들."""
    return [root / _COMMON_DIR, *discover_packs(root)]


def _normalise(text: str) -> str:
    """CRLF를 LF로 맞춘다. `Path.read_text`가 텍스트 모드라 이미 줄바꿈을 변환해 주므로
    디스크에서 읽은 내용에는 사실상 효과가 없다 — overrides로 들어오는, 파일을 거치지 않은
    문자열에도 안전하도록 남겨 둔 보험용 정규화다.
    """
    return text.replace("\r\n", "\n")


def pack_content_hash(pack_dir: Path, *, overrides: dict[Path, str] | None = None) -> str:
    """팩 폴더의 모든 yaml(`examples/*.yaml` 포함)을 상대경로 순서로 묶어 sha256을 낸다.

    `overrides`는 아직 디스크에 쓰지 않은, 이번 생성으로 바뀔 파일의 내용이다(생성 파일 포함).
    `pack.lock`은 `*.yaml`이 아니라 글롭에 걸리지 않아 저절로 빠진다. `.md` 파일도 뺀다.
    디스크 파일은 `utf-8-sig`로 읽어 BOM이 있어도 없는 파일과 같은 해시가 되게 한다.
    """
    overrides = overrides or {}
    # 생성 파일은 아직 디스크에 없을 수도 있어(최초 생성 전), 디스크에 있는 파일과
    # overrides로 받은 파일 경로를 합쳐야 매번 같은 파일 집합을 해시한다.
    override_files = {p for p in overrides if p.suffix == ".yaml" and p.is_relative_to(pack_dir)}
    digest = hashlib.sha256()
    for path in sorted({*pack_dir.rglob("*.yaml"), *override_files}):
        rel = path.relative_to(pack_dir).as_posix()
        text = overrides[path] if path in overrides else path.read_text(encoding="utf-8-sig")
        digest.update(f"{rel}\0".encode())
        digest.update(f"{_normalise(text)}\0".encode())
    return digest.hexdigest()


def lock_content(versions: dict[str, str]) -> str:
    return render({"versions": versions})


def read_lock_versions(pack_dir: Path) -> dict[str, str]:
    """기존 `pack.lock`의 version → sha256 기록. lock이 없으면(최초 생성) 빈 기록."""
    path = pack_dir / LOCK_NAME
    if not path.is_file():
        return {}
    return dict(read_yaml(path).get("versions") or {})


def build_term(
    spec: Record,
    words: dict[str, Record],
    domains: dict[str, Record],
    official: dict[str, dict[str, str]],
    where: str,
) -> Record:
    term = spec["term"]
    composition: list[str] = spec["composition"]
    unknown = [w for w in composition if w not in words]
    if unknown:
        raise BuildError(f"{where} {term}: 사전에 없는 단어 {unknown}")
    row = official.get(term)
    if row:
        physical, domain, source = (
            row["공통표준용어영문약어명"].strip(),
            row["공통표준도메인명"].strip(),
            "official",
        )
    else:
        physical = "_".join(words[w]["abbreviation"] for w in composition)
        domain, source = spec["domain"], "project"
    if domain not in domains:
        raise BuildError(f"{where} {term}: 공식 사전에 없는 도메인 {domain}")
    last = words[composition[-1]]
    if not last["is_classifier"]:
        raise BuildError(f"{where} {term}: 마지막 단어 '{last['word']}'가 분류어가 아님")
    if last["domain_group"] != domains[domain]["class"]:
        raise BuildError(f"{where} {term}: 분류어 '{last['word']}'와 도메인 {domain}의 분류가 다름")
    if len(physical.encode()) > MAX_IDENTIFIER_BYTES:
        raise BuildError(f"{where} {term}: 물리명 {physical}이 63바이트 초과")
    return {
        "term": term,
        "composition": composition,
        "domain": domain,
        "physical_name": physical,
        "source": source,
        "synonyms": spec.get("synonyms") or [],
    }


def render(data: Record) -> str:
    return GENERATED_HEADER + yaml.safe_dump(data, allow_unicode=True, sort_keys=False, width=200)


def unique_physical_names(terms: Iterable[Record], where: str) -> None:
    seen: set[str] = set()
    for t in terms:
        if t["physical_name"] in seen:
            raise BuildError(f"{where}: 물리명 중복 {t['physical_name']}")
        seen.add(t["physical_name"])


def build(root: Path) -> dict[Path, str]:
    """입력을 읽어 생성 파일 경로와 내용을 돌려준다. 파일은 쓰지 않는다."""
    sources = read_yaml(root / "sources/sources.yaml")
    src = root / "sources"
    word_rows = read_csv(src / sources["files"]["words"]["path"])
    domain_rows = read_csv(src / sources["files"]["domains"]["path"])
    official = {
        r["공통표준용어명"].strip(): r for r in read_csv(src / sources["files"]["terms"]["path"])
    }

    all_words = {r["공통표준단어명"].strip(): word_entry(r) for r in word_rows}
    all_domains = {r["공통표준도메인명"].strip(): domain_entry(r) for r in domain_rows}

    outputs: dict[Path, str] = {}
    used_words: set[str] = set()
    used_domains: set[str] = set()
    from specton.packs.selection import SelectionError, validate_selection

    for pack in discover_packs(root):
        project_words = {w["word"]: w for w in read_yaml(pack / "words.yaml").get("words") or []}
        try:
            validate_selection(pack, map(word_entry, word_rows), registered_words=project_words)
        except SelectionError as exc:
            raise BuildError(str(exc)) from exc
        words = {**all_words, **project_words}
        specs = read_yaml(pack / "term_specs.yaml").get("terms") or []
        terms = [build_term(s, words, all_domains, official, pack.name) for s in specs]
        # 이름 충돌이 물리명 충돌보다 원인이 분명하므로 먼저 알린다 (#264). 로더도 같은 함수를 쓴다.
        if problems := term_name_conflicts((t["term"], t["synonyms"]) for t in terms):
            raise BuildError(f"{pack / 'term_specs.yaml'}:\n" + "\n".join(problems))
        unique_physical_names(terms, pack.name)
        used_words |= {w for t in terms for w in t["composition"] if w in all_words}
        used_domains |= {t["domain"] for t in terms}
        outputs[pack / "terms.yaml"] = render({"terms": terms})

    edition = sources["edition"]
    common_words = [w for name, w in all_words.items() if name in used_words or w["is_classifier"]]
    common_domains = [d for name, d in all_domains.items() if name in used_domains]
    outputs[root / "common/words.yaml"] = render({"edition": edition, "words": common_words})
    outputs[root / "common/domains.yaml"] = render(
        {
            "edition": edition,
            "allowed_sql_types": [t.value for t in SqlType],
            "domains": common_domains,
            "on_unknown": "finding",
        }
    )
    outputs.update(_lock_outputs(root, outputs))
    return outputs


def _lock_outputs(root: Path, outputs: dict[Path, str]) -> dict[Path, str]:
    """팩별 `pack.lock`. 이번 생성으로 바뀔 파일은 디스크 대신 `outputs`의 새 내용으로 해시한다.

    `pack.lock`은 version → sha256 기록(history)이다. 같은 version에 다른 해시가 이미
    기록돼 있으면(= 내용은 바뀌었는데 version을 올리지 않음) `BuildError`로 거절한다.
    그 밖에는 이전 기록을 유지하면서 현재 version 항목을 추가/유지한다(lock이 없으면 최초 생성).
    """
    locks: dict[Path, str] = {}
    for pack_dir in all_pack_dirs(root):
        version = read_yaml(pack_dir / "manifest.yaml")["version"]
        content_hash = pack_content_hash(pack_dir, overrides=outputs)
        history = read_lock_versions(pack_dir)
        previous_hash = history.get(version)
        if previous_hash is not None and previous_hash != content_hash:
            raise BuildError(
                f"{pack_dir.name}: 내용이 바뀌었는데 manifest.yaml의 version({version})을 "
                "올리지 않았습니다. version을 올린 뒤 다시 생성하세요"
            )
        history[version] = content_hash
        locks[pack_dir / LOCK_NAME] = lock_content(history)
    return locks


def write(outputs: dict[Path, str]) -> None:
    for path, content in outputs.items():
        path.write_text(content, encoding="utf-8")


def check(root: Path) -> list[Path]:
    """생성 결과와 다른(또는 없는) 파일 목록."""
    return [
        p
        for p, content in build(root).items()
        if not p.exists() or p.read_text(encoding="utf-8") != content
    ]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="도메인 팩 생성")
    parser.add_argument("--root", type=Path, default=DEFAULT_ROOT)
    parser.add_argument("--check", action="store_true", help="생성 파일이 최신인지 검사만 한다")
    args = parser.parse_args(argv)
    try:
        if args.check:
            stale = check(args.root)
            for path in stale:
                print(f"최신 아님: {path}", file=sys.stderr)
            return 1 if stale else 0
        outputs = build(args.root)
        write(outputs)
        print(f"생성 {len(outputs)}개 파일")
        return 0
    except BuildError as e:
        print(f"생성 실패: {e}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
